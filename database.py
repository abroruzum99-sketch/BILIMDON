import os
import json
import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv

load_dotenv(override=True)

DATABASE_URL = os.getenv("DATABASE_URL")


def get_connection(row_factory=None):
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL topilmadi!")
    return psycopg.connect(DATABASE_URL, row_factory=row_factory)


def create_database():
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS questions (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    question TEXT NOT NULL UNIQUE,
                    options TEXT NOT NULL,
                    correct_answer TEXT NOT NULL,
                    category TEXT,
                    image_path TEXT,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    image_source TEXT,
                    image_author TEXT,
                    image_license TEXT,
                    batch_date TEXT,
                    batch_number INTEGER,
                    sent_at TIMESTAMP,
                    archived_at TEXT
                )
            """)
            cur.execute("""
                CREATE INDEX IF NOT EXISTS idx_batch
                ON questions(batch_date, batch_number)
            """)
        conn.commit()
    finally:
        conn.close()


def question_exists(question):
    question = " ".join(question.split()).casefold()
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT question FROM questions")
            rows = cur.fetchall()
        return any(
            " ".join(row[0].split()).casefold() == question
            for row in rows
        )
    finally:
        conn.close()


def add_question(
    question,
    options,
    correct_answer,
    category="Umumiy",
    image_path=None,
    image_source=None,
    image_author=None,
    image_license=None
):
    if question_exists(question):
        print("Bu savol avval mavjud!")
        return False

    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute("""
                INSERT INTO questions (
                    question, options, correct_answer, category,
                    image_path, image_source, image_author, image_license
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
            """, (
                question, json.dumps(options, ensure_ascii=False),
                correct_answer, category, image_path,
                image_source, image_author, image_license
            ))
        conn.commit()
        print("Savol bazaga saqlandi!")
        return True
    except psycopg.errors.UniqueViolation:
        conn.rollback()
        print("Bu savol bazada mavjud!")
        return False
    finally:
        conn.close()


def get_existing_questions(limit=100):
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT question FROM questions
                ORDER BY id DESC LIMIT %s
            """, (limit,))
            rows = cur.fetchall()
        return [row[0] for row in rows]
    finally:
        conn.close()


def assign_questions_to_batch(batch_date, batch_number):
    if batch_number not in (1, 2, 3):
        print("Partiya raqami 1, 2 yoki 3 bo'lishi kerak!")
        return False

    conn = get_connection()
    try:
        with conn.transaction():
            with conn.cursor() as cur:
                cur.execute("""
                    SELECT COUNT(*) FROM questions
                    WHERE batch_date = %s AND batch_number = %s
                """, (batch_date, batch_number))

                if cur.fetchone()[0] > 0:
                    print("Bu partiya avval shakllantirilgan!")
                    return False
                cur.execute("""
                    SELECT id FROM questions
                    WHERE batch_date IS NULL
                    AND (image_path IS NULL OR image_path = '')
                    ORDER BY id LIMIT 19
                    FOR UPDATE
                """)
                normal_ids = [row[0] for row in cur.fetchall()]

                cur.execute("""
                    SELECT id FROM questions
                    WHERE batch_date IS NULL
                    AND image_path IS NOT NULL
                    AND image_path != ''
                    ORDER BY id LIMIT 1
                    FOR UPDATE
                """)
                image_row = cur.fetchone()

                if len(normal_ids) < 19 or image_row is None:
                    print("Partiya uchun savollar yetarli emas!")
                    print("Oddiy savollar:", len(normal_ids), "/19")
                    print("Rasmli savol:", "1/1" if image_row else "0/1")
                    return False

                all_ids = normal_ids + [image_row[0]]

                cur.executemany("""
                    UPDATE questions
                    SET batch_date = %s, batch_number = %s
                    WHERE id = %s
                """, [
                    (batch_date, batch_number, qid)
                    for qid in all_ids
                ])

        print(f"{batch_number}-partiya tayyor!")
        print("Jami savollar: 20")
        print("Oddiy savollar: 19")
        print("Rasmli savollar: 1")
        return True

    except Exception as e:
        print("Partiya yaratishda xatolik:", type(e).name)
        return False
    finally:
        conn.close()


def get_batch_questions(batch_date, batch_number):
    conn = get_connection(dict_row)
    try:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT * FROM questions
                WHERE batch_date = %s AND batch_number = %s
                ORDER BY
                    CASE WHEN image_path IS NULL OR image_path = ''
                    THEN 0 ELSE 1 END,
                    id
            """, (batch_date, batch_number))
            rows = cur.fetchall()

        result = []
        for row in rows:
            item = dict(row)
            item["options"] = json.loads(item["options"])
            result.append(item)
        return result
    finally:
        conn.close()


def mark_question_sent(question_id):
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute("""
                UPDATE questions
                SET sent_at = CURRENT_TIMESTAMP
                WHERE id = %s AND sent_at IS NULL
            """, (question_id,))
            updated = cur.rowcount
        conn.commit()
        return updated == 1
    finally:
        conn.close()


def create_answer_tables():
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute("""
                CREATE TABLE IF NOT EXISTS participants (
                    user_id BIGINT PRIMARY KEY,
                    first_name TEXT,
                    username TEXT,
                    joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """)
            cur.execute("""
                CREATE TABLE IF NOT EXISTS answers (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    user_id BIGINT NOT NULL,
                    question_id BIGINT NOT NULL,
                    batch_date TEXT NOT NULL,
                    batch_number INTEGER NOT NULL,
                    selected_option INTEGER NOT NULL,
                    is_correct INTEGER NOT NULL,
                    answered_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    UNIQUE(user_id, question_id)
                )
                  """)
            cur.execute("""
                CREATE INDEX IF NOT EXISTS idx_answers_batch
                ON answers(batch_date, batch_number)
            """)
            cur.execute("""
                CREATE INDEX IF NOT EXISTS idx_answers_user
                ON answers(user_id, batch_date, batch_number)
            """)
        conn.commit()
        print("Natijalar jadvallari tayyor!")
    finally:
        conn.close()


def save_answer(user_id, first_name, username, question_id,
                batch_date, batch_number, selected_option,
                options, correct_answer):

    is_correct = int(options[selected_option] == correct_answer)
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute("""
                INSERT INTO participants (user_id, first_name, username)
                VALUES (%s, %s, %s)
                ON CONFLICT(user_id) DO UPDATE SET
                    first_name = EXCLUDED.first_name,
                    username = EXCLUDED.username
            """, (user_id, first_name, username))

            cur.execute("""
                INSERT INTO answers (
                    user_id, question_id, batch_date,
                    batch_number, selected_option, is_correct
                )
                VALUES (%s, %s, %s, %s, %s, %s)
                ON CONFLICT(user_id, question_id) DO UPDATE SET
                    selected_option = EXCLUDED.selected_option,
                    is_correct = EXCLUDED.is_correct,
                    answered_at = CURRENT_TIMESTAMP
            """, (
                user_id, question_id, batch_date,
                batch_number, selected_option, is_correct
            ))
        conn.commit()
        return is_correct
    finally:
        conn.close()


def get_daily_leaderboard(batch_date):
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT
                    COALESCE(NULLIF(p.username, ''), p.first_name, 'Ishtirokchi'),
                    COUNT(a.id),
                    SUM(a.is_correct),
                    COUNT(a.id) - SUM(a.is_correct),
                    ROUND(100.0 * SUM(a.is_correct) / COUNT(a.id), 1)
                FROM answers a
                JOIN participants p ON p.user_id = a.user_id
                WHERE a.batch_date = %s
                GROUP BY p.user_id
                ORDER BY
                    SUM(a.is_correct) DESC,
                    ROUND(100.0 * SUM(a.is_correct) / COUNT(a.id), 1) DESC,
                    COUNT(a.id) DESC
            """, (batch_date,))
            return cur.fetchall()
    finally:
        conn.close()


def get_user_batch_result(user_id, batch_date, batch_number):
    conn = get_connection()
    try:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT
                    p.first_name,
                    p.username,
                    COUNT(a.id),
                    COALESCE(SUM(a.is_correct), 0),
                    COUNT(a.id) - COALESCE(SUM(a.is_correct), 0)
                FROM participants p
                LEFT JOIN answers a
                    ON p.user_id = a.user_id
                    AND a.batch_date = %s
                    AND a.batch_number = %s
                WHERE p.user_id = %s
                GROUP BY p.user_id
            """, (batch_date, batch_number, user_id))
            result = cur.fetchone()

        if result is None:
            return None

        first_name, username, total, correct, incorrect = result
        percentage = round(correct * 100 / 20, 1)

        return {
            "first_name": first_name,
            "username": username,
            "total": total,
            "correct": correct,
            "incorrect": incorrect,
            "percentage": percentage
        }
    finally:
        conn.close()
